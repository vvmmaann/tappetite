ALL_BATCHES = [COMEBACK, TECH, AITOOL, AIASK, ADDGAME, GAMESTYLE, JEWELRY, BRANDS]


def main():
    cats = json.loads(P.read_text(encoding="utf-8"))
    by_id = {c.get("id"): c for c in cats}
    summary = []
    coverage_errors = []
    for batch in ALL_BATCHES:
        cid = batch["id"]
        target = by_id.get(cid)
        if not target:
            print(f"SKIP {cid}: not found", file=sys.stderr)
            continue
        item_ids = {it.get("id") for it in (target.get("items") or [])}
        covered = set()
        for arch in batch["archetypes"]:
            for tid in arch.get("triggers", []):
                covered.add(tid)
        missing = item_ids - covered
        if missing:
            coverage_errors.append((cid, missing))
        target["archetypes"] = batch["archetypes"]
        target["defaultArchetype"] = batch["default"]
        summary.append((cid, len(batch["archetypes"])))
    if coverage_errors:
        print("\n!!! COVERAGE ERRORS:", file=sys.stderr)
        for cid, miss in coverage_errors:
            print(f"  {cid}: {sorted(miss)}", file=sys.stderr)
        return 1
    ts = time.strftime("%Y%m%d-%H%M%S")
    bak = P.parent / f"categories.json.bak.personality8.{ts}"
    bak.write_bytes(P.read_bytes())
    tmp = P.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(cats, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(tmp, P)
    print(f"OK. Backup: {bak.name}")
    for cid, n in summary:
        print(f"  {cid}: {n} archetypes + 1 default")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

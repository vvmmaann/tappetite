def main():
    cats = json.loads(P.read_text(encoding="utf-8"))
    found = False
    for c in cats:
        if c.get("id") == "your_philosophy":
            c["archetypes"] = ARCHETYPES
            c["defaultArchetype"] = DEFAULT_ARCHETYPE
            found = True
            break
    if not found:
        print("ERROR: your_philosophy not found")
        return 1

    # Backup + atomic write
    ts = time.strftime("%Y%m%d-%H%M%S")
    bak = P.parent / f"categories.json.bak.philosophy.{ts}"
    bak.write_bytes(P.read_bytes())
    tmp = P.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(cats, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(tmp, P)
    print(f"OK. Wrote {len(ARCHETYPES)} archetypes + improved default. Backup: {bak.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
